from pathlib import Path
from typing import Any


RECORD_LABEL_PATTERNS = [
    r"\b(?:SME|Sony Music|UMG|Universal Music|WMG|Warner Music|BMG|EMI|Avex|Pony Canyon|King Records|Lantis|Aniplex)\b",
    r"\b(?:Tencent Music|TME|NetEase Cloud Music|QQ Music|Kugou|Kuwo|滾石|相信音樂|華研|杰威尔|JVR Music)\b",
    r"\b(?:Licensed to YouTube by|Provided to YouTube by|Auto-generated by YouTube)\b",
    r"\b(?:Official MV|Official Music Video|Official Audio|Lyric Video|Full OST|Original Soundtrack)\b",
]

STUDIO_VISUAL_PATTERNS = [
    r"\b(?:Tencent Video|腾讯视频|iQIYI|爱奇艺|Youku|优酷|MangoTV|芒果TV|Bilibili|哔哩哔哩独家|Netflix|Disney\+|HBO|TVB)\b",
    r"\b(?:Full Movie|Phim lẻ|Phim bộ bản quyền|Official Trailer|Vietsub Bản Quyền)\b",
]

MUSIC_RISK_KEYWORDS = [
    r"\b(?:mv|ost|soundtrack|remix|cover|dj|edm|bgm|nhạc trẻ|nhạc hoa|nhạc nền|тикток музыка|抖音神曲|bgm)\b",
    r"(?:♫|♪|🎵|🎶|🎧)",
]


def _find_ffmpeg() -> str | None:
    bundle = Path(getattr(sys, "_MEIPASS", Path(__file__).resolve().parents[2]))
    binary = bundle / "bin" / "ffmpeg.exe"
    if binary.is_file():
        return str(binary)
    return shutil.which("ffmpeg")


def _probe_video_duration(video_path: Path) -> float:
    executable = _find_ffmpeg()
    ffprobe = str(Path(executable).with_name("ffprobe.exe")) if executable else shutil.which("ffprobe")
    if not ffprobe or not video_path or not video_path.is_file():
        return 0.0
    try:
        res = subprocess.run(
            [
                ffprobe,
                "-v",
                "error",
                "-show_entries",
                "format=duration",
                "-of",
                "default=noprint_wrappers=1:nokey=1",
                str(video_path),
            ],
            capture_output=True,
            text=True,
            timeout=10,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
        return max(0.0, float((res.stdout or "0").strip()))
    except Exception:
        return 0.0


def _recognize_music_free_shazam(audio_bytes: bytes) -> dict[str, Any] | None:
    """Optional free Shazam recognition when shazamio is installed (no API key needed)."""
    if not audio_bytes:
        return None
    try:
        import asyncio
        from shazamio import Shazam  # type: ignore

        async def _run():
            shazam = Shazam()
            return await shazam.recognize(audio_bytes)

        data = asyncio.run(_run())
        track = data.get("track") if isinstance(data, dict) else None
        if not isinstance(track, dict) or not track.get("title"):
            return None
        return {
            "provider": "shazam",
            "title": str(track.get("title") or "").strip(),
            "artist": str(track.get("subtitle") or "").strip(),
            "album": "",
            "label": "",
            "release_date": "",
            "song_link": str(track.get("url") or "").strip(),
            "isrc": str(track.get("isrc") or "").strip(),
        }
    except Exception:
        return None


def _extract_audio_sample_bytes(video_path: Path, start_sec: int = 5, duration_sec: int = 15) -> bytes | None:
    executable = _find_ffmpeg()
    if not executable or not video_path or not video_path.is_file():
        return None
    try:
        result = subprocess.run(
            [
                executable,
                "-nostdin",
                "-v",
                "error",
                "-ss",
                str(max(0, start_sec)),
                "-t",
                str(max(5, min(20, duration_sec))),
                "-i",
                str(video_path),
                "-vn",
                "-ac",
                "1",
                "-ar",
                "16000",
                "-b:a",
                "48k",
                "-f",
                "mp3",
                "-",
            ],
            capture_output=True,
            timeout=25,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
        if result.returncode == 0 and result.stdout and len(result.stdout) <= 2 * 1024 * 1024:
            return result.stdout
    except Exception:
        return None
    return None


def _extract_audio_sample_base64(video_path: Path, start_sec: int = 5, duration_sec: int = 15) -> str | None:
    raw = _extract_audio_sample_bytes(video_path, start_sec=start_sec, duration_sec=duration_sec)
    if raw and len(raw) <= 1024 * 1024:
        return base64.b64encode(raw).decode("ascii")
    return None


def recognize_music_with_audd(audio_bytes: bytes, api_token: str) -> dict[str, Any] | None:
    """Identify exact song title, artist, album, and record label via AudD Audio Fingerprinting."""
    token = str(api_token or "").strip()
    if not token or not audio_bytes:
        return None
    import requests

    response = requests.post(
        "https://api.audd.io/",
        data={"api_token": token, "return": "spotify,apple_music"},
        files={"file": ("sample.mp3", audio_bytes, "audio/mpeg")},
        timeout=25,
    )
    if not response.ok:
        return None
    payload = response.json() if response.content else {}
    if not isinstance(payload, dict) or payload.get("status") != "success":
        return None
    result = payload.get("result")
    if not isinstance(result, dict):
        return None
    spotify = result.get("spotify") if isinstance(result.get("spotify"), dict) else {}
    apple = result.get("apple_music") if isinstance(result.get("apple_music"), dict) else {}
    external_ids = spotify.get("external_ids") if isinstance(spotify.get("external_ids"), dict) else {}
    return {
        "provider": "audd",
        "title": str(result.get("title") or "").strip(),
        "artist": str(result.get("artist") or "").strip(),
        "album": str(result.get("album") or "").strip(),
        "label": str(result.get("label") or apple.get("recordLabel") or "").strip(),
        "release_date": str(result.get("release_date") or "").strip(),
        "song_link": str(result.get("song_link") or "").strip(),
        "isrc": str(external_ids.get("isrc") or apple.get("isrc") or "").strip(),
    }


def recognize_music_with_acrcloud(
    audio_bytes: bytes,
    *,
    host: str,
    access_key: str,
    access_secret: str,
) -> dict[str, Any] | None:
    """Identify exact song & label via ACRCloud Audio Fingerprinting."""
    clean_host = str(host or "").strip().removeprefix("https://").removeprefix("http://").strip("/")
    key = str(access_key or "").strip()
    secret = str(access_secret or "").strip()
    if not (clean_host and key and secret and audio_bytes):
        return None
    import requests

    timestamp = str(int(time.time()))
    string_to_sign = "\n".join(["POST", "/v1/identify", key, "audio", "1", timestamp])
    signature = base64.b64encode(
        hmac.new(secret.encode("utf-8"), string_to_sign.encode("utf-8"), digestmod=hashlib.sha1).digest()
    ).decode("ascii")

    response = requests.post(
        f"https://{clean_host}/v1/identify",
        data={
            "access_key": key,
            "sample_bytes": str(len(audio_bytes)),
            "timestamp": timestamp,
            "signature": signature,
            "data_type": "audio",
            "signature_version": "1",
        },
        files={"sample": ("sample.mp3", audio_bytes, "audio/mpeg")},
        timeout=25,
    )
    if not response.ok:
        return None
    payload = response.json() if response.content else {}
    music_list = ((payload.get("metadata") or {}).get("music") or []) if isinstance(payload, dict) else []
    if not music_list:
        return None
    top = music_list[0] if isinstance(music_list[0], dict) else {}
    artists = ", ".join(str(a.get("name") or "") for a in (top.get("artists") or []) if isinstance(a, dict) and a.get("name"))
    external_ids = top.get("external_ids") if isinstance(top.get("external_ids"), dict) else {}
    return {
        "provider": "acrcloud",
        "title": str(top.get("title") or "").strip(),
        "artist": artists,
        "album": str(((top.get("album") or {}).get("name")) or "").strip(),
        "label": str(top.get("label") or "").strip(),
        "release_date": str(top.get("release_date") or "").strip(),
        "song_link": "",
        "isrc": str(external_ids.get("isrc") or "").strip(),
    }


def _extract_frame_base64(video_path: Path, seconds: int = 4) -> str | None:
    executable = _find_ffmpeg()
    if not executable or not video_path or not video_path.is_file():
        return None
    try:
        result = subprocess.run(
            [
                executable,
                "-nostdin",
                "-v",
                "error",
                "-ss",
                str(max(0, seconds)),
                "-i",
                str(video_path),
                "-frames:v",
                "1",
                "-vf",
                "scale=960:540:force_original_aspect_ratio=decrease",
                "-q:v",
                "5",
                "-f",
                "image2pipe",
                "-",
            ],
            capture_output=True,
            timeout=20,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
        if result.returncode == 0 and result.stdout and len(result.stdout) <= 1024 * 1024:
            return base64.b64encode(result.stdout).decode("ascii")
    except Exception:
        return None
    return None


def analyze_heuristic_copyright_risk(
    *,
    title: str = "",
    description: str = "",
    url: str = "",
    mode: str = "voiceover",
    original_volume: float = 0.15,
    music_url: str = "",
    auto_brand_blur: bool = False,
    has_blur_region: bool = False,
    track: str = "",
    artist: str = "",
    license_name: str = "",
) -> dict[str, Any]:
    combined_text = f"{title or ''}\n{description or ''}\n{track or ''}\n{artist or ''}".strip()

    music_reasons: list[str] = []
    visual_reasons: list[str] = []
    warnings: list[str] = []
    recommendations: list[str] = []

    music_score = 15
    visual_score = 15

    # 1. Kiểm tra thông tin bài hát / hãng đĩa
    if track and not re.search(r"(?:original sound|nhạc nền gốc|âm thanh gốc|原声)", track, re.I):
        music_score += 50
        music_reasons.append(f"Phát hiện bản nhạc đính kèm: “{track}”{f' - {artist}' if artist else ''}.")

    for pattern in RECORD_LABEL_PATTERNS:
        match = re.search(pattern, combined_text, re.I)
        if match:
            music_score += 55
            music_reasons.append(f"Phát hiện dấu hiệu bản quyền âm nhạc/hãng đĩa (“{match.group(0)}”).")
            break

    for pattern in MUSIC_RISK_KEYWORDS:
        match = re.search(pattern, combined_text, re.I)
        if match:
            music_score += 25
            music_reasons.append(f"Tiêu đề/mô tả có từ khóa nhạc hoặc OST (“{match.group(0)}”).")
            break

    if music_url:
        music_score += 25
        music_reasons.append("Đang chèn thêm link nhạc nền ngoài — hãy đảm bảo nhạc không dính Content ID.")

    if license_name and "creative commons" in license_name.lower():
        music_score = max(10, music_score - 25)
        visual_score = max(10, visual_score - 25)

    # 2. Kiểm tra dấu hiệu hình ảnh / đài truyền hình / nền tảng
    for pattern in STUDIO_VISUAL_PATTERNS:
        match = re.search(pattern, combined_text, re.I)
        if match:
            visual_score += 40
            visual_reasons.append(f"Nguồn có dấu hiệu phim/hoạt hình/đài lớn (“{match.group(0)}”).")
            break

    if any(host in (url or "").lower() for host in ("bilibili.com", "b23.tv", "douyin.com", "iqiyi.com", "qq.com", "youku.com")):
        visual_score += 20
        visual_reasons.append("Video từ nền tảng Trung Quốc (Bilibili/Douyin…) thường có logo góc hoặc nhạc nền BGM dễ trùng Content ID.")

    # 3. Đánh giá mức độ bảo vệ của cấu hình xử lý hiện tại
    is_subtitle_only = str(mode or "").lower() == "subtitle"
    orig_vol = float(original_volume if original_volume is not None else (1.0 if is_subtitle_only else 0.15))

    if is_subtitle_only:
        music_score += 35
        warnings.append(
            "Chế độ 'Chỉ Phụ đề (Sub)' giữ nguyên 100% âm thanh và nhạc gốc của video — nguy cơ bị YouTube bắt Content ID âm nhạc rất cao nếu video gốc có nhạc nền."
        )
        recommendations.append(
            "Chuyển sang chế độ 'Voice + Phụ đề (Lồng tiếng AI)' và hạ Âm lượng gốc xuống 0% – 8% để triệt tiêu dấu vân tay âm thanh (Audio Fingerprint)."
        )
    elif orig_vol > 0.20:
        music_score += 25
        warnings.append(
            f"Âm lượng gốc đang để khá cao ({round(orig_vol * 100)}%) — YouTube Content ID vẫn có thể nhận diện được nhạc nền phía sau giọng đọc."
        )
        recommendations.append(
            "Hạ 'Âm lượng gốc' xuống dưới 8% (hoặc 0% nếu video gốc có nhạc bản quyền mạnh)."
        )
    else:
        # Đã lồng tiếng AI và hạ nhỏ âm gốc -> giảm mạnh nguy cơ bản quyền nhạc
        music_score = max(12, music_score - 30)
        music_reasons.append(
            f"Đã bật Lồng tiếng AI và hạ âm lượng gốc xuống {round(orig_vol * 100)}% (giúp giảm mạnh rủi ro trùng khớp nhạc Content ID)."
        )

    if not auto_brand_blur and not has_blur_region:
        visual_score += 15
        recommendations.append(
            "Bật 'Làm mờ watermark/logo' hoặc khoanh vùng làm mờ logo kênh gốc để tránh trùng khớp hình ảnh."
        )
    else:
        visual_score = max(10, visual_score - 15)
        visual_reasons.append("Đã bật làm mờ vùng phụ đề / logo nguồn.")

    music_score = min(98, max(5, music_score))
    visual_score = min(98, max(5, visual_score))
    overall_score = round(max(music_score, visual_score) * 0.7 + min(music_score, visual_score) * 0.3)

    def level_from_score(score: int) -> str:
        if score >= 65:
            return "high"
        if score >= 38:
            return "medium"
        return "low"

    music_risk = level_from_score(music_score)
    visual_risk = level_from_score(visual_score)
    overall_risk = level_from_score(overall_score)

    if music_risk == "high":
        warnings.insert(0, "⚠️ Cảnh báo: Nguy cơ cao dính bản quyền Âm nhạc (YouTube Content ID Audio Claim).")
    if visual_risk == "high":
        warnings.append("⚠️ Cảnh báo: Hình ảnh video có nguy cơ trùng khớp bản quyền phim/chương trình hoặc chứa logo nhà đài.")

    if not warnings and overall_risk == "medium":
        warnings.append("Lưu ý: Video có khả năng chứa nhạc nền hoặc watermark gốc. Nên dùng Lồng tiếng AI và hạ nhỏ âm gốc trước khi đăng YouTube.")

    if not recommendations:
        recommendations.append("Cấu hình hiện tại đã tối ưu tốt (Lồng tiếng AI + hạ âm gốc + che vùng mờ). Có thể xuất và đăng an toàn.")

    return {
        "overall_risk": overall_risk,
        "overall_score": overall_score,
        "music_risk": music_risk,
        "music_score": music_score,
        "visual_risk": visual_risk,
        "visual_score": visual_score,
        "detected_music": track or ("Có dấu hiệu nhạc trong tiêu đề/mô tả" if music_score >= 45 else "Chưa phát hiện bài hát thương mại rõ ràng"),
        "music_reasons": music_reasons or ["Chưa phát hiện dấu hiệu nhạc bản quyền trong metadata."],
        "visual_reasons": visual_reasons or ["Hình ảnh ở mức rủi ro thông thường."],
        "warnings": warnings,
        "recommendations": recommendations,
        "ai_scanned": False,
        "safe_config_patch": {
            "mode": "voiceover",
            "original_volume": 0.05,
            "voice_volume": 1.15,
            "auto_brand_blur": True,
        },
    }


def check_video_copyright(
    *,
    video_path: Path | None = None,
    title: str = "",
    description: str = "",
    url: str = "",
    mode: str = "voiceover",
    original_volume: float = 0.15,
    music_url: str = "",
    auto_brand_blur: bool = False,
    has_blur_region: bool = False,
    use_ai: bool = True,
    audd_api_token: str = "",
    acrcloud_host: str = "",
    acrcloud_access_key: str = "",
    acrcloud_access_secret: str = "",
) -> dict[str, Any]:
    result = analyze_heuristic_copyright_risk(
        title=title,
        description=description,
        url=url,
        mode=mode,
        original_volume=original_volume,
        music_url=music_url,
        auto_brand_blur=auto_brand_blur,
        has_blur_region=has_blur_region,
    )

    if not use_ai:
        return result

    # 1) Audio Fingerprinting (AudD / ACRCloud) to identify exact song & record label
    audd_token = (audd_api_token or os.getenv("AUDD_API_TOKEN") or "").strip()
    acr_host = (acrcloud_host or os.getenv("ACRCLOUD_HOST") or "").strip()
    acr_key = (acrcloud_access_key or os.getenv("ACRCLOUD_ACCESS_KEY") or "").strip()
    acr_secret = (acrcloud_access_secret or os.getenv("ACRCLOUD_ACCESS_SECRET") or "").strip()

    recognized = None
    if video_path and video_path.is_file():
        for start_s in (4, 22):
            clip_bytes = _extract_audio_sample_bytes(video_path, start_sec=start_s, duration_sec=12)
            if not clip_bytes:
                continue
            try:
                if audd_token:
                    recognized = recognize_music_with_audd(clip_bytes, audd_token)
                if not recognized and acr_host and acr_key and acr_secret:
                    recognized = recognize_music_with_acrcloud(
                        clip_bytes,
                        host=acr_host,
                        access_key=acr_key,
                        access_secret=acr_secret,
                    )
                if not recognized:
                    recognized = _recognize_music_free_shazam(clip_bytes)
            except Exception:
                recognized = None
            if recognized:
                break

    if recognized:
        result["recognized_track"] = recognized
        song_title = recognized.get("title") or "Bài hát chưa rõ tên"
        song_artist = recognized.get("artist") or "Chưa rõ nghệ sĩ"
        song_label = recognized.get("label") or ""
        label_suffix = f" · Hãng: {song_label}" if song_label else ""
        result["detected_music"] = f"{song_title} — {song_artist}{label_suffix}"
        has_major_label = bool(song_label and re.search(
            r"(?:Sony|Universal|Warner|SME|UMG|WMG|EMI|BMG|Believe|Tencent|NetEase|Avex|Pony Canyon|Lantis|Aniplex|JVR)",
            song_label,
            re.IGNORECASE,
        ))
        high_orig = mode == "subtitle" or float(original_volume) > 0.12
        if high_orig:
            result["music_score"] = max(result["music_score"], 90 if has_major_label else 82)
            result["music_risk"] = "high"
            result["overall_score"] = max(result["overall_score"], 84)
            result["overall_risk"] = "high"
            result["warnings"].insert(
                0,
                f"Phát hiện bài hát bản quyền: \"{song_title}\" - {song_artist}{label_suffix}. Giữ âm gốc cao rất dễ dính YouTube Content ID!",
            )
            result["recommendations"].insert(0, "Chuyển sang Voice + Phụ đề và hạ Âm lượng audio gốc xuống 0%–5% để tránh Content ID Audio.")
        else:
            result["music_score"] = max(result["music_score"], 45 if has_major_label else 35)
            if result["music_score"] >= 38 and result["music_risk"] == "low":
                result["music_risk"] = "medium"
            result["warnings"].insert(
                0,
                f"Nhận diện được nhạc nền: \"{song_title}\" - {song_artist}{label_suffix}. Đã giảm âm gốc nhưng vẫn nên giữ ≤ 5%.",
            )
        result["ai_scanned"] = True
        result["scan_note"] = f"Đã nhận diện nhạc bằng {recognized.get('provider', 'fingerprint').upper()}."

    try:
        from services.gemini_oauth import authorized_request, get_project_id
        from services.assistant_service import _MODELS, is_model_exhausted, mark_model_exhausted

        project = get_project_id()
        if not project:
            return result

        parts: list[dict[str, Any]] = [
            {
                "text": json.dumps(
                    {
                        "title": str(title or "")[:300],
                        "description": str(description or "")[:600],
                        "source_url": str(url or "")[:300],
                        "process_mode": mode,
                        "original_volume": original_volume,
                        "auto_brand_blur": auto_brand_blur,
                    },
                    ensure_ascii=False,
                )
            }
        ]

        if video_path and video_path.is_file():
            audio_b64 = _extract_audio_sample_base64(video_path, start_sec=4, duration_sec=14)
            if audio_b64:
                parts.append({"inlineData": {"mimeType": "audio/mp3", "data": audio_b64}})
            duration_s = _probe_video_duration(video_path)
            frame_marks = [3]
            if duration_s >= 25:
                frame_marks.extend([max(8, int(duration_s * 0.4)), max(15, int(duration_s * 0.75))])
            for sec in frame_marks[:3]:
                frame_b64 = _extract_frame_base64(video_path, seconds=sec)
                if frame_b64:
                    parts.append({"inlineData": {"mimeType": "image/jpeg", "data": frame_b64}})

        system_prompt = (
            "Bạn là chuyên gia kiểm tra bản quyền YouTube Content ID (Video Hình ảnh & Âm nhạc) cho hệ thống ReupAI. "
            "Hãy phân tích mẫu âm thanh (nếu có), các khung hình video ở nhiều mốc thời gian (nếu có), tiêu đề và cấu hình xử lý để đánh giá nguy cơ dính bản quyền trên YouTube. "
            "Đặc biệt kiểm tra: (1) Nhạc nền, bài hát thương mại có lời/OST; (2) Hình ảnh phim truyền hình, anime, show TV, MV gốc, logo nhà đài/nền tảng (Tencent Video, iQIYI, Youku, MangoTV, Bilibili, Netflix, TVB, VTV...) hoặc watermark bản quyền. "
            "Trả về đúng JSON với các trường: "
            "music_risk ('low'|'medium'|'high'), "
            "visual_risk ('low'|'medium'|'high'), "
            "overall_risk ('low'|'medium'|'high'), "
            "detected_music (chuỗi tiếng Việt ngắn mô tả bài hát/nhạc nền phát hiện được), "
            "warnings (mảng tối đa 3 cảnh báo ngắn gọn bằng tiếng Việt nêu rõ nguy cơ nhạc & hình ảnh nếu có), "
            "recommendations (mảng tối đa 3 cách khắc phục cụ thể bằng tiếng Việt)."
        )

        body = {
            "systemInstruction": {"parts": [{"text": system_prompt}]},
            "contents": [{"role": "user", "parts": parts}],
            "generationConfig": {"temperature": 0.2, "responseMimeType": "application/json"},
        }

        response = None
        for model in _MODELS:
            if is_model_exhausted(model):
                continue
            response = authorized_request(
                "POST",
                f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent",
                project_id=project,
                json=body,
                timeout=45,
            )
            if response.status_code in {404, 429}:
                mark_model_exhausted(model)
                continue
            if response.ok or response.status_code not in {500, 502, 503, 504}:
                break

        if response is not None and response.ok:
            raw_text = "".join(
                p.get("text", "") for p in response.json()["candidates"][0]["content"]["parts"]
            )
            ai_data = json.loads(raw_text)
            valid_levels = {"low", "medium", "high"}
            rank = {"low": 1, "medium": 2, "high": 3}

            ai_music = str(ai_data.get("music_risk", "")).lower()
            ai_visual = str(ai_data.get("visual_risk", "")).lower()
            ai_overall = str(ai_data.get("overall_risk", "")).lower()

            if ai_music in valid_levels and rank[ai_music] > rank[result["music_risk"]]:
                result["music_risk"] = ai_music
                result["music_score"] = max(result["music_score"], 75 if ai_music == "high" else 48)
            if ai_visual in valid_levels and rank[ai_visual] > rank[result["visual_risk"]]:
                result["visual_risk"] = ai_visual
                result["visual_score"] = max(result["visual_score"], 75 if ai_visual == "high" else 48)
            if ai_overall in valid_levels and rank[ai_overall] > rank[result["overall_risk"]]:
                result["overall_risk"] = ai_overall
                result["overall_score"] = max(result["overall_score"], 78 if ai_overall == "high" else 50)

            if ai_data.get("detected_music"):
                result["detected_music"] = str(ai_data["detected_music"]).strip()[:200]
            if isinstance(ai_data.get("warnings"), list) and ai_data["warnings"]:
                merged_w = [str(w).strip() for w in ai_data["warnings"] if str(w).strip()]
                for w in result["warnings"]:
                    if w not in merged_w:
                        merged_w.append(w)
                result["warnings"] = merged_w[:4]
            if isinstance(ai_data.get("recommendations"), list) and ai_data["recommendations"]:
                merged_r = [str(r).strip() for r in ai_data["recommendations"] if str(r).strip()]
                for r in result["recommendations"]:
                    if r not in merged_r:
                        merged_r.append(r)
                result["recommendations"] = merged_r[:4]
            result["ai_scanned"] = True
    except Exception:
        pass

    return result
