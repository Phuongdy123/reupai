export const ALL_TTS_VOICES = [
  ...VIETNAMESE_TTS_VOICES.map((v) => ({ ...v, lang: "vi" })),
  ...ENGLISH_TTS_VOICES,
  ...MULTILANG_TTS_VOICES,
];

export function voicesForTargetLanguage(targetLang = "vi") {
  const code = String(targetLang || "vi").trim().toLowerCase() || "vi";
  const matched = ALL_TTS_VOICES.filter((v) => v.lang === code);
  return matched.length ? matched : VIETNAMESE_TTS_VOICES.map((v) => ({ ...v, lang: "vi" }));
}

export function defaultVoiceForLanguage(targetLang = "vi") {
  return voicesForTargetLanguage(targetLang)[0]?.value || "Trúc Ly";
}

export function isVoiceCompatibleWithLanguage(voice, targetLang = "vi") {
  const code = String(targetLang || "vi").trim().toLowerCase() || "vi";
  return voicesForTargetLanguage(code).some((v) => v.value === voice);
}

export function renderVoiceOptionsHtml(targetLang = "vi") {
  return voicesForTargetLanguage(targetLang)
    .map((v) => `<option value="${v.value}">${v.label}</option>`)
    .join("\n");
}

